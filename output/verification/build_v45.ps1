$source = 'C:\Users\hu\Desktop\测试.nes'
$target = 'C:\Users\hu\Desktop\测试_敌方武器跨UI复合CHR修复V45.nes'
$reference = 'D:\GIT\mmc3\output\verification\v45-rebuilt-from-test.nes'
$rom = [IO.File]::ReadAllBytes($source)
$chrBase = 0x80010

function Copy-ChrBank([int]$sourceBank, [int]$targetBank) {
    [Array]::Copy($rom, $chrBase + $sourceBank * 0x400,
        $rom, $chrBase + $targetBank * 0x400, 0x400)
}
function Copy-ChrTile([int]$sourceBank, [int]$sourceTile,
        [int]$targetBank, [int]$targetTile) {
    [Array]::Copy($rom, $chrBase + $sourceBank * 0x400 + $sourceTile * 16,
        $rom, $chrBase + $targetBank * 0x400 + $targetTile * 16, 16)
}

# 敌方紫色武器：顶部 tile $86-$A9 来自 R4=$BB。
# 为顶部和 UI 分别建立内容等价的 R4/R5 复合页。
Copy-ChrBank 0xBB 0xB8
Copy-ChrBank 0xBF 0xB9
Copy-ChrBank 0x02 0xBA
Copy-ChrBank 0x12 0xB5
for ($tile = 0x86; $tile -le 0xA9; $tile++) {
    $targetTile = $tile + 0x33 # $86-$A9 -> $B9-$DC
    $sourceLocal = $tile - 0x80
    if ($targetTile -lt 0xC0) {
        Copy-ChrTile 0xBB $sourceLocal 0xB8 ($targetTile - 0x80)
        Copy-ChrTile 0xBB $sourceLocal 0xBA ($targetTile - 0x80)
    } else {
        Copy-ChrTile 0xBB $sourceLocal 0xB9 ($targetTile - 0xC0)
        Copy-ChrTile 0xBB $sourceLocal 0xB5 ($targetTile - 0xC0)
    }
}

# 保持原入口语义；跨界处理移到最终 OAM 生成之后。
[Array]::Copy([byte[]](0xA9,0x04,0x85,0x15), 0, $rom, 0x7D0F5, 4)

# 扫描战斗 OAM $0240-$02FF：只重编号实际进入 UI 的敌方武器 tile。
$routine = [byte[]](
    0xA0,0x00,0xA2,0x40,
    0xBD,0x00,0x02,0xC9,0x78,0x90,0x17,0xC9,0xF0,0xB0,0x13,
    0xBD,0x01,0x02,0xC9,0x86,0x90,0x0C,0xC9,0xAA,0xB0,0x08,
    0x18,0x69,0x33,0x9D,0x01,0x02,0xA0,0xFF,
    0xE8,0xE8,0xE8,0xE8,0xD0,0xDC,0x60
)
[Array]::Copy($routine, 0, $rom, 0x7F477, $routine.Length)

# 保存调用方 X/Y；命中时切换到复合页，未命中直接恢复现场。
$wrapper = [byte[]](
    0x8A,0x48,0x98,0x48,0x20,0x67,0xF4,0x98,
    0x30,0x03,0x4C,0x65,0xFF,0x4C,0x3B,0xF5
)
[Array]::Copy($wrapper, 0, $rom, 0x7F521, $wrapper.Length)

# 顶部 R4/R5 使用复合页。
$setupTop = [byte[]](
    0xA9,0xB8,0x8D,0xDC,0x04,
    0xA9,0xB9,0x8D,0xDD,0x04,
    0x4C,0x94,0xF4
)
[Array]::Copy($setupTop, 0, $rom, 0x7F54B, $setupTop.Length)

# UI 前两段 R4 使用内容等价的 $BA；其余 IRQ 行保持原值。
$setupUiR4 = [byte[]](
    0xA2,0x01,0xA9,0xBA,0x9D,0xE4,0x03,0xCA,0x10,0xFA,
    0x4C,0xF6,0xF4
)
[Array]::Copy($setupUiR4, 0, $rom, 0x7F4A4, $setupUiR4.Length)

# UI 前两段 R5 使用内容等价的 $B5。
$setupUiR5 = [byte[]](
    0xA2,0x01,0xA9,0xB5,0x9D,0xEE,0x03,0xCA,0x10,0xFA,0x60
)
[Array]::Copy($setupUiR5, 0, $rom, 0x7F506, $setupUiR5.Length)

$finish = [byte[]](0x68,0xA8,0x68,0xAA,0xA5,0x73,0x38,0x60)
[Array]::Copy($finish, 0, $rom, 0x7FF75, $finish.Length)
