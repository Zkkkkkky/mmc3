$rom = [IO.File]::ReadAllBytes($source)
$chrBase = 0x80010

function Copy-ChrBank([int]$sourceBank,[int]$targetBank) {
    [Array]::Copy($rom,$chrBase+$sourceBank*0x400,$rom,$chrBase+$targetBank*0x400,0x400)
}
function Copy-ChrTile([int]$sourceBank,[int]$sourceTile,[int]$targetBank,[int]$targetTile) {
    [Array]::Copy($rom,$chrBase+$sourceBank*0x400+$sourceTile*16,
        $rom,$chrBase+$targetBank*0x400+$targetTile*16,16)
}

# 战斗专用复合页：完整保留原 R4/R5 页，只在未用的 $B9-$DC 槽复制紫色武器。
Copy-ChrBank 0xB7 0xB8
Copy-ChrBank 0xBD 0xB9
Copy-ChrBank 0x02 0xBA
Copy-ChrBank 0x14 0xB5
for($tile=0x06;$tile -le0x29;$tile++) {
    $target=$tile+0xB3
    if($target -lt0xC0) {
        Copy-ChrTile 0xA2 $tile 0xB8 ($target-0x80)
        Copy-ChrTile 0xA2 $tile 0xBA ($target-0x80)
    } else {
        Copy-ChrTile 0xA2 $tile 0xB9 ($target-0xC0)
        Copy-ChrTile 0xA2 $tile 0xB5 ($target-0xC0)
    }
}

