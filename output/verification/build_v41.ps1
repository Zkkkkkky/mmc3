$source = 'C:\Users\hu\Downloads\测试.nes'
$target = 'C:\Users\hu\Downloads\测试_武器跨UI正确显示重做V41.nes'
$reference = 'D:\GIT\mmc3\output\verification\v41-rebuilt-from-test.nes'
$rom = [IO.File]::ReadAllBytes($source)

# 恢复测试 ROM 的原入口，不沿用旧版在这里的提前检测。
[Array]::Copy([byte[]](0xA9,0x04,0x85,0x15), 0, $rom, 0x7D0F5, 4)

# 扫描最终 OAM 的战斗槽；Y=$78-$EF 表示 8x8 拼图已经接触/进入 UI。
$detector = [byte[]](
    0xA2,0x40,0xBD,0x00,0x02,0xC9,0x78,0x90,0x04,0xC9,0xF0,0x90,0x09,
    0xE8,0xE8,0xE8,0xE8,0xD0,0xEF,0xA0,0x00,0x60,
    0xA0,0xFF,0x60
)
[Array]::Copy($detector, 0, $rom, 0x7F477, $detector.Length)

# 保存调用方 X/Y；检测命中时同步 UI 行 R0，未命中时进入保持/离场恢复逻辑。
$wrapper = [byte[]](
    0x8A,0x48,0x98,0x48,0x20,0x67,0xF4,0x98,
    0x30,0x03,0x4C,0x22,0xF5,0x4C,0x3B,0xF5
)
[Array]::Copy($wrapper, 0, $rom, 0x7F521, $wrapper.Length)

# 无跨界：$03BE 仍为原值 $08 就直接返回；已启用则等离开战斗再恢复。
$holdGate = [byte[]](
    0xAD,0xBE,0x03,0xC9,0x08,0xF0,0x03,0x4C,0xA8,0xF4,0x4C,0x65,0xFF
)
[Array]::Copy($holdGate, 0, $rom, 0x7F532, $holdGate.Length)

# 命中：只同步真正覆盖 UI 的 IRQ 第 3 行 R0；不改 R1、PPUCTRL、头像或光标。
$enable = [byte[]](0xAD,0xD8,0x04,0x8D,0xBE,0x03,0x4C,0x65,0xFF)
[Array]::Copy($enable, 0, $rom, 0x7F54B, $enable.Length)

# 顶部 R0 为负表示仍在战斗展示，继续保持；离场后把 UI 行 R0 恢复为 $08。
$sceneGate = [byte[]](0xAD,0xD8,0x04,0x10,0x03,0x4C,0x65,0xFF,0xA9,0x08,0x8D,0xBE,0x03,0x4C,0x65,0xFF)
[Array]::Copy($sceneGate, 0, $rom, 0x7F4B8, $sceneGate.Length)

$finish = [byte[]](0x68,0xA8,0x68,0xAA,0xA5,0x73,0x38,0x60)
[Array]::Copy($finish, 0, $rom, 0x7FF75, $finish.Length)
[Array]::Copy([byte[]](0x20,0x11,0xF5), 0, $rom, 0x7FB2C, 3)

[IO.File]::WriteAllBytes($target, $rom)
[IO.File]::WriteAllBytes($reference, $rom)
Get-FileHash -Algorithm SHA256 -LiteralPath $target
